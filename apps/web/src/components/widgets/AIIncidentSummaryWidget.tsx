import { useEffect, useState } from 'react';
import { Link } from 'react-router-dom';
import { Sparkles } from 'lucide-react';
import { Badge, StatusPill, cn } from '@aegisdrive/ui';
import { relativeTime } from '@aegisdrive/shared';
import {
  useCommandCentreIncidents,
  useIncidentSummary,
} from '@/features/command-centre/command-centre.queries';
import { routes } from '@/config/routes';
import { Widget } from './Widget';

/**
 * AI incident summary.
 *
 * Narrates the currently selected open incident. Defaults to the most severe
 * one, because that is the incident an operator arriving at a desk needs
 * explained first.
 *
 * The summary is labelled as model output throughout and kept visually distinct
 * from operator-written text. Conflating the two would make it impossible,
 * months later, to establish whether a human or a model characterised an event
 * — which matters when the record is produced in evidence.
 */
export function AIIncidentSummaryWidget() {
  const incidents = useCommandCentreIncidents({ openOnly: true, limit: 8 });
  const [selectedId, setSelectedId] = useState<string | null>(null);

  const items = incidents.data?.items ?? [];

  // Follow the most severe incident until the operator picks one explicitly,
  // then hold their choice — re-selecting under them mid-read would be hostile.
  useEffect(() => {
    if (selectedId && items.some((incident) => incident.id === selectedId)) return;
    setSelectedId(items[0]?.id ?? null);
  }, [items, selectedId]);

  const summary = useIncidentSummary(selectedId);
  const selected = items.find((incident) => incident.id === selectedId);

  return (
    <Widget
      title="AI incident summary"
      subtitle="Model narration of the active incident"
      isLoading={incidents.isLoading}
      error={incidents.error}
      isEmpty={!incidents.isLoading && items.length === 0}
      emptyTitle="No open incidents"
      emptyDescription="When an incident is raised, the summariser explains it here."
      onRetry={() => void incidents.refetch()}
      className="h-full"
      actions={
        summary.data ? (
          <Badge tone="accent">
            <Sparkles className="size-3" aria-hidden />
            {summary.data.modelId}
          </Badge>
        ) : null
      }
    >
      <div className="space-y-3">
        {items.length > 1 ? (
          <div className="flex flex-wrap gap-1" role="tablist" aria-label="Open incidents">
            {items.slice(0, 6).map((incident) => (
              <button
                key={incident.id}
                type="button"
                role="tab"
                aria-selected={incident.id === selectedId}
                onClick={() => setSelectedId(incident.id)}
                className={cn(
                  'rounded-pill border px-2 py-0.5 text-[10px] font-medium transition-colors',
                  incident.id === selectedId
                    ? 'border-aegis-500/35 bg-aegis-500/12 text-aegis-100'
                    : 'border-hairline bg-white/3 text-ink-tertiary hover:text-ink-secondary',
                )}
              >
                <span data-numeric>{incident.reference.split('-').pop()}</span>
              </button>
            ))}
          </div>
        ) : null}

        {selected ? (
          <div className="flex items-center gap-2">
            <StatusPill
              status={{ kind: 'severity', value: selected.severity }}
              size="sm"
              pulse={selected.severity === 'CRITICAL'}
            />
            <StatusPill status={{ kind: 'incident', value: selected.status }} size="sm" />
            <Link
              to={routes.incidentDetail(selected.id)}
              data-numeric
              className="ml-auto text-[10px] font-semibold text-aegis-300 hover:underline"
            >
              {selected.reference}
            </Link>
          </div>
        ) : null}

        {summary.isLoading ? (
          <p className="text-[11px] text-ink-tertiary">Generating summary…</p>
        ) : summary.data ? (
          <div className="space-y-3">
            <div>
              <p className="text-xs font-semibold text-ink-primary">{summary.data.headline}</p>
              {/* Left rule marks machine-generated prose, so it is never
                  mistaken for an operator's own note. */}
              <p className="mt-1.5 border-l-2 border-aegis-500/40 pl-2.5 text-[11px] leading-relaxed text-ink-secondary">
                {summary.data.narrative}
              </p>
            </div>

            <Section title="Key findings" items={summary.data.keyFindings} />
            <Section title="Suggested next steps" items={summary.data.suggestedNextSteps} accent />

            <p className="border-t border-hairline pt-2 text-[10px] text-ink-tertiary">
              Generated by <code className="text-aegis-300">{summary.data.modelId}</code> at{' '}
              {(summary.data.confidence * 100).toFixed(0)}% confidence ·{' '}
              {relativeTime(summary.data.generatedAt)}. Model output — verify before acting.
            </p>
          </div>
        ) : null}
      </div>
    </Widget>
  );
}

function Section({
  title,
  items,
  accent = false,
}: {
  title: string;
  items: string[];
  accent?: boolean;
}) {
  if (items.length === 0) return null;

  return (
    <div>
      <p className="text-[10px] font-semibold uppercase tracking-[0.1em] text-ink-tertiary">
        {title}
      </p>
      <ul className="mt-1 space-y-1">
        {items.map((item, index) => (
          <li
            key={index}
            className={cn(
              'flex gap-1.5 text-[11px] leading-relaxed',
              accent ? 'text-aegis-100' : 'text-ink-secondary',
            )}
          >
            <span aria-hidden className={accent ? 'text-aegis-400' : 'text-ink-tertiary'}>
              {accent ? '→' : '•'}
            </span>
            {item}
          </li>
        ))}
      </ul>
    </div>
  );
}
